/**
 * 한다체 → 합니다체 변환 검사
 *
 * 노트 원본을 통째로 고치는 변환이라, 규칙이 어긋나면 9천 문장이 한꺼번에 상한다.
 * 실제 노트에서 가장 많이 나온 종결 스물다섯 가지를 그대로 담는다.
 */
import { toPoliteSentence, toPoliteText } from "./llm/lib/politeStyle";

const CASES: Array<[string, string]> = [
  // ~ㄴ다 (모음 어간 동사)
  ["W를 켜고 평타를 넣는다.", "W를 켜고 평타를 넣습니다."],
  ["궁극기로 진입을 끊는다.", "궁극기로 진입을 끊습니다."],
  ["상대가 라인을 민다.", "상대가 라인을 밉니다."],
  ["방패가 다시 차오른다.", "방패가 다시 차오릅니다."],
  ["체력을 채운다.", "체력을 채웁니다."],
  ["표식을 남긴다.", "표식을 남깁니다."],
  ["거리를 둔다.", "거리를 둡니다."],
  ["피해를 준다.", "피해를 줍니다."],
  ["쿨이 돌아온다.", "쿨이 돌아옵니다."],
  ["기회를 만든다.", "기회를 만듭니다."],
  ["스킬이 빗나간다.", "스킬이 빗나갑니다."],
  ["둔화가 걸린다.", "둔화가 걸립니다."],
  ["교전이 끝난다.", "교전이 끝납니다."],
  ["버튼을 누른다.", "버튼을 누릅니다."],
  ["마나를 쓴다.", "마나를 씁니다."],
  ["효과가 사라진다.", "효과가 사라집니다."],
  ["체력이 깎인다.", "체력이 깎입니다."],
  ["궁을 빼낸다.", "궁을 빼냅니다."],
  // ~는다 (자음 어간 동사)
  ["포탑 사거리 안에서 먹는다.", "포탑 사거리 안에서 먹습니다."],
  ["상대 정글을 읽는다.", "상대 정글을 읽습니다."],
  // 형용사·지정사
  ["딜 교환이 유리하다.", "딜 교환이 유리합니다."],
  ["이 구간이 제일 강하다.", "이 구간이 제일 강합니다."],
  ["대응할 방법이 없다.", "대응할 방법이 없습니다."],
  ["보호막이 남아 있다.", "보호막이 남아 있습니다."],
  ["물러나는 편이 낫다.", "물러나는 편이 낫습니다."],
  ["사거리가 크다.", "사거리가 큽니다."],
  ["핵심은 타이밍이다.", "핵심은 타이밍입니다."],
  ["서두를 일이 아니다.", "서두를 일이 아닙니다."],
  ["점화가 들어가면 위험하다.", "점화가 들어가면 위험합니다."],
  ["스킬이 맞물려 돌아간다.", "스킬이 맞물려 돌아갑니다."],
  // 손대지 않는 것
  ["이미 합니다체입니다.", "이미 합니다체입니다."],
  ["W를 켠 뒤에 붙으십시오.", "W를 켠 뒤에 붙으십시오."],
  ["궁을 아껴 두고", "궁을 아껴 두고"],
];

let failed = 0;
for (const [input, want] of CASES) {
  const got = toPoliteSentence(input);
  if (got !== want) {
    failed += 1;
    console.error(`✖ ${input}\n   기대 ${want}\n   실제 ${got}`);
  }
}

// 여러 문장이 이어진 글
const long = "W는 다음 평타를 강화한다. E는 상대 공격 속도를 깎으니 나중에 쓴다. 물몸 상대는 한 사이클에 정리된다.";
const wantLong = "W는 다음 평타를 강화합니다. E는 상대 공격 속도를 깎으니 나중에 씁니다. 물몸 상대는 한 사이클에 정리됩니다.";
if (toPoliteText(long) !== wantLong) {
  failed += 1;
  console.error(`✖ 여러 문장\n   기대 ${wantLong}\n   실제 ${toPoliteText(long)}`);
}

if (failed > 0) {
  console.error(`\n${failed}건 실패`);
  process.exit(1);
}
console.log(`✅ 합니다체 변환 통과 (${CASES.length + 1}건)`);
